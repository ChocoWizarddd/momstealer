package com.nightlight.app.shuffle;

import com.nightlight.app.domain.model.Track;
import com.nightlight.app.smartshuffle.GenreHelper;
import com.nightlight.app.smartshuffle.TitleGuard;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Random;
import java.util.Set;

/**
 * The one canonical shuffle implementation.
 *
 * <p>Both strategies return EVERY pool track EXACTLY ONCE. That
 * completeness is the whole point: the queue consumes the order as a
 * window and must never be able to run dry mid-cycle.
 *
 * <ul>
 *   <li>{@link #plainOrder} — uniform Fisher-Yates, unbiased.</li>
 *   <li>{@link #smartOrder} — the canonical Smart order. Several
 *       complete seeded permutations are generated by constrained
 *       placement, each is scored on the soft diversity terms (artist
 *       spacing, album spacing, genre diversity, title similarity,
 *       freshness and recent plays), and the best-scoring candidate is
 *       returned.</li>
 * </ul>
 *
 * <p>Track uniqueness is the ONLY hard rule. Artist spacing, album
 * spacing, genre diversity and freshness are SOFT penalties: a pool
 * that cannot be spread — five of twelve tracks from one artist, a
 * wall of one song's covers — is relaxed automatically and still
 * produces a complete, valid order. The algorithm never rejects a
 * playable pool; it returns the best permutation it can build.
 *
 * <p>This class is pure Java on purpose (unit-testable, no Android
 * imports). Diagnostics of the last {@link #smartOrder} run are
 * exposed for the Android side to log; they are best-effort and may
 * be stale if smartOrder has not run yet.
 */
public final class ShuffleOrderFactory {

    private static final double TEMPERATURE = 1.0;
    private static final double W_ARTIST_RECENT = 0.55;
    private static final double W_ALBUM_RECENT = 0.35;
    private static final double W_GENRE_RUN = 0.30;
    private static final double W_TITLE_RECENT = 0.50;
    private static final double W_FRESHNESS = 1.9;
    private static final double W_GENRE_BALANCE = 2.2;

    /** An artist never returns within this many tracks when alternatives exist. */
    static final int ARTIST_WINDOW = 8;
    /** Albums vary almost as strictly as artists, so a shorter window. */
    static final int ALBUM_WINDOW = 4;
    /** Same-song adjacency is repaired across this many tracks. */
    static final int TITLE_WINDOW = 4;

    /** Golden-ratio stride: distinct, reproducible seeds per candidate. */
    private static final long SEED_STRIDE = 0x9E3779B97F4A7C15L;

    /** Candidates generated per smartOrder call, by pool size. */
    private static final int CANDIDATES_SMALL = 8;   // <= 300 tracks
    private static final int CANDIDATES_MEDIUM = 5;  // <= 1000
    private static final int CANDIDATES_LARGE = 3;   // <= 2500
    private static final int CANDIDATES_HUGE = 2;    // > 2500

    /** Diagnostics of the most recent smartOrder() run (Android-side logging). */
    private static volatile int lastPoolSize;
    private static volatile int lastCandidateCount;
    private static volatile double lastBestScore;

    private ShuffleOrderFactory() {
    }

    public static List<String> plainOrder(List<Track> pool, long seed) {
        List<String> ids = ids(pool);
        shuffleInPlace(ids, new Random(seed));
        return ids;
    }

    /**
     * The canonical Smart order: generate several complete seeded
     * permutations and return the one that scores best on the soft
     * diversity terms. Always a complete permutation of the pool —
     * soft preferences are relaxed, never enforced by rejection.
     */
    public static List<String> smartOrder(List<Track> pool, long seed, List<String> recentlyPlayedIds) {
        List<Track> remaining = dedup(pool);
        List<String> out = new ArrayList<>(remaining.size());
        if (remaining.isEmpty()) {
            lastPoolSize = 0;
            lastCandidateCount = 0;
            lastBestScore = 0;
            return out;
        }

        int candidates = candidateCount(remaining.size());
        List<String> best = null;
        double bestScore = Double.NEGATIVE_INFINITY;
        int bestAdjacency = Integer.MAX_VALUE;
        Map<String, Track> byId = byId(remaining);
        for (int k = 0; k < candidates; k++) {
            List<String> candidate = sampleOrder(remaining,
                    seed + SEED_STRIDE * (k + 1), recentlyPlayedIds);
            double score = scoreOrder(candidate, remaining, recentlyPlayedIds);
            // Score ties (possible when a pool carries no genre or
            // album signal) are broken by the strongest local clumping
            // signal: immediate same-artist or same-song repeats.
            int adjacency = immediateAdjacency(candidate, byId);
            if (score > bestScore
                    || (score == bestScore && adjacency < bestAdjacency)) {
                bestScore = score;
                best = candidate;
                bestAdjacency = adjacency;
            }
        }

        lastPoolSize = remaining.size();
        lastCandidateCount = candidates;
        lastBestScore = bestScore;
        return best;
    }

    /** Diagnostics of the last {@link #smartOrder} run. */
    public static int lastPoolSize() {
        return lastPoolSize;
    }

    public static int lastCandidateCount() {
        return lastCandidateCount;
    }

    public static double lastBestScore() {
        return lastBestScore;
    }

    private static int candidateCount(int n) {
        if (n <= 300) return CANDIDATES_SMALL;
        if (n <= 1000) return CANDIDATES_MEDIUM;
        if (n <= 2500) return CANDIDATES_LARGE;
        return CANDIDATES_HUGE;
    }

    private static Map<String, Track> byId(List<Track> pool) {
        Map<String, Track> map = new HashMap<>(pool.size() * 2);
        for (Track t : pool) map.put(t.id, t);
        return map;
    }

    /**
     * Immediate same-artist or same-song repeats — the strongest
     * local clumping signal. Used only to break score ties, never
     * to reject: a pool that cannot be spread still scores and wins
     * on its other terms.
     */
    private static int immediateAdjacency(List<String> order, Map<String, Track> byId) {
        int count = 0;
        for (int i = 1; i < order.size(); i++) {
            Track prev = byId.get(order.get(i - 1));
            Track cur = byId.get(order.get(i));
            if (prev == null || cur == null) continue;
            String prevArtist = TitleGuard.norm(prev.artists);
            String curArtist = TitleGuard.norm(cur.artists);
            if (!prevArtist.isEmpty() && prevArtist.equals(curArtist)) count++;
            String prevTitle = TitleGuard.canonicalTitle(prev.name);
            String curTitle = TitleGuard.canonicalTitle(cur.name);
            if (!prevTitle.isEmpty() && prevTitle.equals(curTitle)) count++;
        }
        return count;
    }

    /**
     * One complete permutation via weighted sampling without
     * replacement. Same-artist and same-song adjacency are hard-filtered
     * whenever an alternative exists, and allowed only when the pool
     * leaves no choice — which is what stops a search wall of one
     * song's covers from playing back to back. Genre runs and
     * recently-played tracks stay soft, so the result still feels
     * random rather than alternating and predictable.
     */
    private static List<String> sampleOrder(List<Track> pool, long seed,
                                             List<String> recentlyPlayedIds) {
        List<Track> remaining = new ArrayList<>(pool);
        List<String> out = new ArrayList<>(remaining.size());

        Random rng = new Random(seed);
        Set<String> fresh = new LinkedHashSet<>();
        if (recentlyPlayedIds != null) {
            for (String id : recentlyPlayedIds) {
                if (id != null && !id.isEmpty()) fresh.add(id);
            }
        }

        Set<String> distinctArtists = new HashSet<>();
        Set<String> distinctAlbums = new HashSet<>();
        for (Track t : remaining) {
            String a = TitleGuard.norm(t.artists);
            if (!a.isEmpty()) distinctArtists.add(a);
            String al = TitleGuard.norm(t.album);
            if (!al.isEmpty()) distinctAlbums.add(al);
        }
        // A cooldown window only applies when the pool holds enough distinct
        // artists/albums to honor it; otherwise it degrades to a plain spread.
        int artistWindow = distinctArtists.size() > 1
                ? Math.min(ARTIST_WINDOW, distinctArtists.size()) : 0;
        int albumWindow = distinctAlbums.size() > 1
                ? Math.min(ALBUM_WINDOW, distinctAlbums.size()) : 0;
        int titleWindow = Math.min(TITLE_WINDOW, remaining.size());

        Map<String, Integer> remainingByGenre = new HashMap<>();
        for (Track t : remaining) {
            remainingByGenre.merge(genreOf(t), 1, Integer::sum);
        }
        Map<String, Integer> placedByGenre = new HashMap<>();

        List<String> recentArtists = new ArrayList<>();
        List<String> recentAlbums = new ArrayList<>();
        List<String> recentTitles = new ArrayList<>();
        String runGenre = null;
        int runLength = 0;

        while (!remaining.isEmpty()) {
            String lastArtist = recentArtists.isEmpty() ? null : recentArtists.get(0);
            String lastTitle = recentTitles.isEmpty() ? null : recentTitles.get(0);
            List<Integer> candidates = eligible(remaining, lastArtist, lastTitle);

            double remainingTotal = remaining.size();
            double placedTotal = out.size();
            int remainingCount = remainingByGenre.size();
            int placedCount = placedByGenre.size();

            double[] weights = new double[candidates.size()];
            double totalWeight = 0;

            for (int i = 0; i < candidates.size(); i++) {
                Track t = remaining.get(candidates.get(i));
                String artist = TitleGuard.norm(t.artists);
                String albumKey = TitleGuard.norm(t.album);
                String title = TitleGuard.canonicalTitle(t.name);
                String genre = genreOf(t);
                double penalty = 0;

                if (artistWindow > 0 && !recentArtists.isEmpty()) {
                    int span = Math.min(artistWindow, recentArtists.size());
                    for (int j = 0; j < span; j++) {
                        if (recentArtists.get(j).equals(artist)) {
                            penalty += W_ARTIST_RECENT * (1.0 - (double) j / span);
                            break;
                        }
                    }
                }
                if (albumWindow > 0 && !recentAlbums.isEmpty()) {
                    int span = Math.min(albumWindow, recentAlbums.size());
                    for (int j = 0; j < span; j++) {
                        if (recentAlbums.get(j).equals(albumKey)) {
                            penalty += W_ALBUM_RECENT * (1.0 - (double) j / span);
                            break;
                        }
                    }
                }
                for (int j = 0; j < Math.min(titleWindow, recentTitles.size()); j++) {
                    String rt = recentTitles.get(j);
                    if (!rt.isEmpty() && rt.equals(title)) {
                        penalty += W_TITLE_RECENT * (1.0 - (double) j / Math.max(1, titleWindow));
                        break;
                    }
                }
                if (genre.equals(runGenre)) {
                    penalty += W_GENRE_RUN * runLength;
                } else if (runLength >= 3) {
                    penalty += W_GENRE_RUN * 0.5;
                }
                if (fresh.contains(t.id)) {
                    penalty += W_FRESHNESS;
                }

                double balance = genreBalance(genre, remainingByGenre, placedByGenre,
                        remainingTotal, placedTotal, remainingCount, placedCount);

                double w = Math.exp((balance - penalty) / TEMPERATURE);
                if (!(w > 1e-9)) w = 1e-9;
                weights[i] = w;
                totalWeight += w;
            }

            int candidateIdx;
            if (!(totalWeight > 0) || Double.isNaN(totalWeight)) {
                candidateIdx = rng.nextInt(candidates.size());
            } else {
                double r = rng.nextDouble() * totalWeight;
                candidateIdx = candidates.size() - 1;
                for (int i = 0; i < candidates.size(); i++) {
                    r -= weights[i];
                    if (r <= 0) { candidateIdx = i; break; }
                }
            }

            int chosenIdx = candidates.get(candidateIdx);
            Track chosen = remaining.remove(chosenIdx);
            out.add(chosen.id);

            String chosenGenre = genreOf(chosen);
            remainingByGenre.computeIfPresent(chosenGenre, (k, v) -> v - 1);
            placedByGenre.merge(chosenGenre, 1, Integer::sum);

            pushWindow(recentArtists, TitleGuard.norm(chosen.artists), Math.max(1, artistWindow));
            pushWindow(recentAlbums, TitleGuard.norm(chosen.album), Math.max(1, albumWindow));
            pushWindow(recentTitles, TitleGuard.canonicalTitle(chosen.name), titleWindow);

            if (chosenGenre.equals(runGenre)) {
                runLength++;
            } else {
                runGenre = chosenGenre;
                runLength = 1;
            }
        }
        return out;
    }

    /**
     * Scores a COMPLETE order on the soft diversity terms. Higher is
     * better (the score is the negated penalty total).
     *
     * <p>Every term is soft: nothing here can reject an order. A pool
     * that cannot be spread simply scores lower, and the caller picks
     * the best candidate it has.
     *
     * <ul>
     *   <li>artist spacing — same artist inside {@link #ARTIST_WINDOW}
     *       costs more the closer it is,</li>
     *   <li>album spacing — same album inside {@link #ALBUM_WINDOW},</li>
     *   <li>genre diversity — same-genre runs plus prefixes that
     *       over-represent a genre against its share of the pool,</li>
     *   <li>title similarity — same canonical title inside
     *       {@link #TITLE_WINDOW},</li>
     *   <li>freshness — a history track reappearing early costs more
     *       the more recently it was heard (history is oldest-first,
     *       newest last),</li>
     *   <li>recent plays — any history track inside the opening third
     *       of the order adds a flat penalty.</li>
     * </ul>
     */
    static double scoreOrder(List<String> order, List<Track> pool,
                               List<String> recentlyPlayedIds) {
        int n = order.size();
        if (n == 0) return 0;
        Map<String, Track> byId = new HashMap<>(n * 2);
        for (Track t : pool) byId.put(t.id, t);

        String[] artists = new String[n];
        String[] albums = new String[n];
        String[] titles = new String[n];
        String[] genres = new String[n];
        for (int i = 0; i < n; i++) {
            Track t = byId.get(order.get(i));
            artists[i] = TitleGuard.norm(t.artists);
            albums[i] = TitleGuard.norm(t.album);
            titles[i] = TitleGuard.canonicalTitle(t.name);
            genres[i] = genreOf(t);
        }

        double penalty = 0;

        penalty += proximityPenalty(artists, ARTIST_WINDOW, W_ARTIST_RECENT);
        penalty += proximityPenalty(albums, ALBUM_WINDOW, W_ALBUM_RECENT);
        penalty += proximityPenalty(titles, TITLE_WINDOW, W_TITLE_RECENT);

        // Genre diversity: runs plus prefix over-representation.
        Map<String, Integer> globalGenre = new HashMap<>();
        for (String g : genres) globalGenre.merge(g, 1, Integer::sum);
        Map<String, Integer> placedGenre = new HashMap<>();
        int run = 1;
        for (int i = 0; i < n; i++) {
            if (i > 0) {
                run = genres[i].equals(genres[i - 1]) ? run + 1 : 1;
                if (run > 1) penalty += W_GENRE_RUN * (run - 1);
            }
            placedGenre.merge(genres[i], 1, Integer::sum);
            int prefix = i + 1;
            for (Map.Entry<String, Integer> e : globalGenre.entrySet()) {
                double expected = e.getValue() / (double) n;
                double actual = placedGenre.getOrDefault(e.getKey(), 0) / (double) prefix;
                double over = actual - expected;
                if (over > 0) penalty += W_GENRE_BALANCE * over / n;
            }
        }

        // Freshness and recent plays. The history is oldest-first, so the
        // newest track carries the largest recency weight. Soft: history
        // tracks stay eligible — they are only pushed later, never dropped.
        if (recentlyPlayedIds != null && !recentlyPlayedIds.isEmpty()) {
            Map<String, Double> recency = new HashMap<>();
            int h = recentlyPlayedIds.size();
            for (int i = 0; i < h; i++) {
                String id = recentlyPlayedIds.get(i);
                if (id != null && !id.isEmpty()) {
                    recency.put(id, (i + 1) / (double) h);
                }
            }
            int openingThird = Math.max(1, n / 3);
            for (int i = 0; i < n; i++) {
                Double recencyWeight = recency.get(order.get(i));
                if (recencyWeight == null) continue;
                penalty += W_FRESHNESS * recencyWeight * (n - i) / n;
                if (i < openingThird) penalty += W_FRESHNESS * 0.5;
            }
        }

        return -penalty;
    }

    /** Same-key proximity penalty inside a sliding window, closer = worse. */
    private static double proximityPenalty(String[] keys, int window, double weight) {
        double penalty = 0;
        for (int i = 1; i < keys.length; i++) {
            String key = keys[i];
            if (key.isEmpty()) continue;
            for (int j = Math.max(0, i - window); j < i; j++) {
                if (key.equals(keys[j])) {
                    penalty += weight * (window - (i - j)) / (double) window;
                }
            }
        }
        return penalty;
    }

    /**
     * Lifts genres that are behind their remaining share and damps genres that
     * are ahead of it, so proportions hold across every prefix of the order.
     */
    private static double genreBalance(String genre, Map<String, Integer> remainingByGenre,
                                        Map<String, Integer> placedByGenre, double remainingTotal,
                                        double placedTotal, int remainingCount, int placedCount) {
        if (remainingCount <= 1) return 0;
        // Nothing placed yet means no share to diverge from, so there is nothing
        // to correct — the very first pick is always unbiased.
        if (placedTotal <= 0 || placedCount <= 0) return 0;
        double remainingShare = remainingByGenre.getOrDefault(genre, 0) / remainingTotal;
        double placedShare = placedByGenre.getOrDefault(genre, 0) / placedTotal;
        // Floor keeps a not-yet-placed genre finite instead of infinite.
        double floor = 0.5 / placedTotal;
        if (placedShare < floor) placedShare = floor;
        return W_GENRE_BALANCE * (Math.log(remainingShare) - Math.log(placedShare));
    }

    /**
     * Candidate positions for the next pick, as a relaxation ladder.
     *
     * <ol>
     *   <li>neither the previous song nor the previous artist repeats,</li>
     *   <li>the previous song does not repeat (same artist allowed),</li>
     *   <li>the previous artist does not repeat (same song allowed),</li>
     *   <li>anything left, so a single-artist or one-song pool still ends.</li>
     * </ol>
     *
     * <p>Song identity is protected harder than artist identity on purpose: a
     * search wall of one song's covers playing back to back is far more jarring
     * than one artist appearing twice, and the ladder must not trade a song
     * repeat away just because the only song-alternative happens to share the
     * previous artist. Step 2 is what prevents that.
     */
    private static List<Integer> eligible(List<Track> remaining, String lastArtist, String lastTitle) {
        boolean hasArtist = lastArtist != null && !lastArtist.isEmpty();
        boolean hasTitle = lastTitle != null && !lastTitle.isEmpty();
        if (hasArtist || hasTitle) {
            List<Integer> strict = filter(remaining, lastArtist, lastTitle, true, true);
            if (!strict.isEmpty()) return strict;
            List<Integer> noTitleRepeat = filter(remaining, lastArtist, lastTitle, false, true);
            if (!noTitleRepeat.isEmpty()) return noTitleRepeat;
            List<Integer> noArtistRepeat = filter(remaining, lastArtist, lastTitle, true, false);
            if (!noArtistRepeat.isEmpty()) return noArtistRepeat;
        }
        List<Integer> all = new ArrayList<>(remaining.size());
        for (int i = 0; i < remaining.size(); i++) all.add(i);
        return all;
    }

    private static List<Integer> filter(List<Track> remaining, String lastArtist, String lastTitle,
                                           boolean blockArtist, boolean blockTitle) {
        List<Integer> out = new ArrayList<>(remaining.size());
        for (int i = 0; i < remaining.size(); i++) {
            Track t = remaining.get(i);
            if (blockArtist && lastArtist != null && !lastArtist.isEmpty()
                    && lastArtist.equals(TitleGuard.norm(t.artists))) continue;
            if (blockTitle && lastTitle != null && !lastTitle.isEmpty()
                    && lastTitle.equals(TitleGuard.canonicalTitle(t.name))) continue;
            out.add(i);
        }
        return out;
    }

    private static void pushWindow(List<String> window, String value, int size) {
        if (value == null || value.isEmpty()) return;
        window.add(0, value);
        while (window.size() > Math.max(1, size)) window.remove(window.size() - 1);
    }

    static void shuffleInPlace(List<String> ids, Random rng) {
        for (int i = ids.size() - 1; i > 0; i--) {
            int j = rng.nextInt(i + 1);
            Collections.swap(ids, i, j);
        }
    }

    static List<String> ids(List<Track> pool) {
        List<String> out = new ArrayList<>();
        if (pool == null) return out;
        Set<String> seen = new HashSet<>();
        for (Track t : pool) {
            if (t == null || t.id == null || t.id.isEmpty()) continue;
            if (seen.add(t.id)) out.add(t.id);
        }
        return out;
    }

    private static String genreOf(Track t) {
        return GenreHelper.genreOf(t);
    }

    private static List<Track> dedup(List<Track> pool) {
        List<Track> out = new ArrayList<>();
        if (pool == null) return out;
        Set<String> seen = new HashSet<>();
        for (Track t : pool) {
            if (t == null || t.id == null || t.id.isEmpty()) continue;
            if (seen.add(t.id)) out.add(t);
        }
        return out;
    }
}
